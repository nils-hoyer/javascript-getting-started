// Arrays – Lösungen

// Aufgabe 1
const sizes = ["S", "M", "L", "XL"];
console.log(sizes);

// Aufgabe 2
console.log(sizes[0]); // "S"

// Aufgabe 3
sizes[0] = "XS";
console.log(sizes); // ["XS", "M", "L", "XL"]

// Aufgabe 4
sizes.push("XXL");
console.log(sizes); // ["XS", "M", "L", "XL", "XXL"]

// Aufgabe 5
sizes.pop();
console.log(sizes); // ["XS", "M", "L", "XL"]
